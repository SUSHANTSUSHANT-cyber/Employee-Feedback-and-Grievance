BEGIN;

CREATE TABLE IF NOT EXISTS grievance_status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grievance_id INTEGER NOT NULL,
    previous_status TEXT,
    new_status TEXT NOT NULL,
    changed_by TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    remarks TEXT,
    CONSTRAINT fk_grievance_status_history_grievance
        FOREIGN KEY (grievance_id)
        REFERENCES interaction_logs(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS grievance_status_history_grievance_id_idx
ON grievance_status_history (grievance_id);

CREATE INDEX IF NOT EXISTS grievance_status_history_changed_at_idx
ON grievance_status_history (changed_at);

CREATE INDEX IF NOT EXISTS grievance_status_history_grievance_id_changed_at_idx
ON grievance_status_history (grievance_id, changed_at ASC);

-- Idempotent backfill: ensure existing grievances have an initial registration record
INSERT INTO grievance_status_history (grievance_id, previous_status, new_status, changed_by, changed_at, remarks)
SELECT
    l.id,
    NULL,
    COALESCE(NULLIF(l.status, ''), 'Pending Review'),
    'system',
    CASE 
        WHEN l.timestamp > 0 THEN TO_TIMESTAMP(l.timestamp / 1000.0)
        ELSE NOW()
    END,
    'Initial registration (migrated record)'
FROM interaction_logs l
WHERE NOT EXISTS (
    SELECT 1 FROM grievance_status_history h WHERE h.grievance_id = l.id
);

COMMIT;
