-- =============================================================================
-- Employee Assistant Database Schema
-- Target Database: PostgreSQL 18+ (employee_assistant)
-- Application: FastAPI + SQLAlchemy 2.0
-- Idempotent, production-grade schema definition for a fresh installation.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. EMPLOYEES TABLE
-- Stores employee master directory synchronized with Android and import files.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS employees (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    department TEXT NOT NULL,
    "attendanceStatus" TEXT,
    "checkInTime" TEXT,
    "avatarSeed" TEXT,
    "isActive" BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS employees_active_idx
ON employees ("isActive");


-- -----------------------------------------------------------------------------
-- 2. CUSTOM CATEGORIES TABLE
-- Service categories for grievances and kiosk navigation.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS custom_categories (
    name TEXT PRIMARY KEY,
    "iconName" TEXT NOT NULL,
    "colorHex" TEXT NOT NULL,
    "displayOrder" INTEGER NOT NULL DEFAULT 0,
    email TEXT NOT NULL DEFAULT '',
    "nameHi" TEXT NOT NULL DEFAULT '',
    "nameJa" TEXT NOT NULL DEFAULT '',
    "isActive" BOOLEAN NOT NULL DEFAULT TRUE,
    "employeeCodeRequired" BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS categories_active_idx
ON custom_categories ("isActive");


-- -----------------------------------------------------------------------------
-- 3. CUSTOM PRESETS TABLE
-- Quick-select prompt suggestions linked to parent categories.
-- Cascades on category name update to support category renames.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS custom_presets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "categoryName" TEXT NOT NULL,
    "textEn" TEXT NOT NULL,
    "textHi" TEXT NOT NULL,
    "textJa" TEXT NOT NULL DEFAULT '',
    "displayOrder" INTEGER NOT NULL DEFAULT 0,
    "isActive" BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_custom_presets_category
        FOREIGN KEY ("categoryName")
        REFERENCES custom_categories(name)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS presets_active_idx
ON custom_presets ("isActive");

CREATE INDEX IF NOT EXISTS presets_category_name_idx
ON custom_presets ("categoryName");


-- -----------------------------------------------------------------------------
-- 4. INTERACTION LOGS TABLE
-- Grievance logs and kiosk interactions synchronized with Android Room database.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interaction_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "complaintNumber" TEXT NOT NULL DEFAULT '',
    "employeeId" TEXT NOT NULL DEFAULT '',
    "employeeName" TEXT NOT NULL DEFAULT '',
    "employeeDept" TEXT NOT NULL DEFAULT '',
    "queryText" TEXT NOT NULL DEFAULT '',
    "responseText" TEXT NOT NULL DEFAULT '',
    "departmentCategory" TEXT NOT NULL DEFAULT '',
    timestamp BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending Review',
    "aiResponse" TEXT NOT NULL DEFAULT '',
    "categoryName" TEXT NOT NULL DEFAULT '',
    "routingInfo" TEXT NOT NULL DEFAULT '',
    "isSynced" BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS interaction_logs_employee_idx
ON interaction_logs ("employeeId");

CREATE INDEX IF NOT EXISTS interaction_logs_category_idx
ON interaction_logs ("categoryName");

CREATE INDEX IF NOT EXISTS interaction_logs_department_category_idx
ON interaction_logs ("departmentCategory");

CREATE INDEX IF NOT EXISTS interaction_logs_timestamp_idx
ON interaction_logs (timestamp);

-- Partial unique index ensures unique non-empty complaint numbers while allowing empty strings
CREATE UNIQUE INDEX IF NOT EXISTS interaction_logs_complaint_number_unique
ON interaction_logs ("complaintNumber")
WHERE "complaintNumber" <> '';


-- -----------------------------------------------------------------------------
-- 5. DELETED GRIEVANCES (TOMBSTONES) TABLE
-- Records deleted complaint numbers to prevent client sync resurrection.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS deleted_grievances (
    "complaintNumber" TEXT PRIMARY KEY,
    "deletedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS deleted_grievances_deleted_at_idx
ON deleted_grievances ("deletedAt");


-- -----------------------------------------------------------------------------
-- 6. ADMIN CONFIGURATION TABLE
-- Singleton configuration record (id = 1) for system settings, emails, branding.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_config (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    "adminPasscode" TEXT NOT NULL DEFAULT '',
    "centralSyncUrl" TEXT NOT NULL DEFAULT '',
    "commonEmail" TEXT NOT NULL DEFAULT '',
    "hrEmail" TEXT NOT NULL DEFAULT '',
    "itEmail" TEXT NOT NULL DEFAULT '',
    "facilitiesEmail" TEXT NOT NULL DEFAULT '',
    "financeEmail" TEXT NOT NULL DEFAULT '',
    "generalEmail" TEXT NOT NULL DEFAULT '',
    "smtpHost" TEXT NOT NULL DEFAULT '',
    "smtpPort" TEXT NOT NULL DEFAULT '',
    "senderEmail" TEXT NOT NULL DEFAULT '',
    "senderPassword" TEXT NOT NULL DEFAULT '',
    "themeColor" TEXT NOT NULL DEFAULT '#173D72',
    "logoName" TEXT NOT NULL DEFAULT 'aisin'
);


-- -----------------------------------------------------------------------------
-- 7. ADMIN USERS TABLE
-- Single master admin account with PBKDF2 hashed credentials.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_users (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    username TEXT NOT NULL UNIQUE CHECK (username = 'admin'),
    "passwordHash" TEXT NOT NULL,
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- -----------------------------------------------------------------------------
-- 8. ADMIN SESSIONS TABLE
-- Opaque server-side session tokens with automatic cascade on admin deletion.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_sessions (
    "tokenHash" TEXT PRIMARY KEY,
    "adminId" INTEGER NOT NULL,
    "expiresAt" TIMESTAMPTZ NOT NULL,
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_admin_sessions_admin
        FOREIGN KEY ("adminId")
        REFERENCES admin_users(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS admin_sessions_expires_at_idx
ON admin_sessions ("expiresAt");


-- -----------------------------------------------------------------------------
-- 9. HISTORICAL MIGRATION BACKUP TABLE
-- Compatible structure for interaction logs duplicate backup (used in test fixtures).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interaction_logs_duplicate_backup (
    LIKE interaction_logs INCLUDING DEFAULTS
);


-- -----------------------------------------------------------------------------
-- 10. GRIEVANCE STATUS HISTORY TABLE
-- Audit log recording grievance lifecycle and all status transitions.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS grievance_status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grievance_id INTEGER NOT NULL,
    previous_status TEXT,
    new_status TEXT NOT NULL,
    changed_by TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    remarks TEXT,
    CONSTRAINT fk_grievance_status_history_grievance
        FOREIGN KEY (grievance_id)
        REFERENCES interaction_logs(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS grievance_status_history_grievance_id_idx
ON grievance_status_history (grievance_id);

CREATE INDEX IF NOT EXISTS grievance_status_history_changed_at_idx
ON grievance_status_history (changed_at);

CREATE INDEX IF NOT EXISTS grievance_status_history_grievance_id_changed_at_idx
ON grievance_status_history (grievance_id, changed_at ASC);
